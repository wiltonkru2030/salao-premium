-- Estrutura aditiva para orçamentos e atendimentos agrupados.
-- Não altera nem remove os agendamentos existentes.
create table if not exists public.quote_settings (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null unique references public.organizations(id) on delete cascade,
  max_discount_percent numeric(5,2) not null default 0 check (max_discount_percent between 0 and 100),
  allow_fixed_discount boolean not null default true,
  updated_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.quote_discount_services (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations(id) on delete cascade,
  service_id uuid not null references public.services(id) on delete restrict,
  discount_allowed boolean not null default false,
  created_at timestamptz not null default now(),
  unique (org_id, service_id)
);
create table if not exists public.quotes (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations(id) on delete cascade,
  branch_id uuid references public.branches(id) on delete set null,
  customer_id uuid not null references public.customers(id) on delete restrict,
  quote_number bigint generated by default as identity,
  status text not null default 'draft' check (status in ('draft','pending','accepted','rejected','expired','cancelled')),
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  discount_total numeric(12,2) not null default 0 check (discount_total >= 0),
  total numeric(12,2) not null default 0 check (total >= 0),
  valid_until date,
  notes text,
  public_token_hash text unique,
  created_by uuid references auth.users(id),
  accepted_at timestamptz,
  rejected_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (org_id, quote_number),
  check (discount_total <= subtotal),
  check (total = subtotal - discount_total)
);
create table if not exists public.quote_items (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations(id) on delete cascade,
  quote_id uuid not null references public.quotes(id) on delete cascade,
  service_id uuid not null references public.services(id) on delete restrict,
  professional_id uuid references public.professionals(id) on delete set null,
  description text not null,
  quantity numeric(10,3) not null default 1 check (quantity > 0),
  duration_minutes integer not null default 30 check (duration_minutes > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  discount_amount numeric(12,2) not null default 0 check (discount_amount >= 0),
  total numeric(12,2) not null check (total >= 0),
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  check (discount_amount <= quantity * unit_price),
  check (total = quantity * unit_price - discount_amount)
);
create index if not exists quote_discount_services_org_service_idx on public.quote_discount_services(org_id, service_id);
create index if not exists quotes_org_status_created_idx on public.quotes(org_id, status, created_at desc);
create index if not exists quotes_org_customer_idx on public.quotes(org_id, customer_id, created_at desc);
create index if not exists quote_items_org_quote_idx on public.quote_items(org_id, quote_id, sort_order);
create index if not exists quote_items_professional_idx on public.quote_items(org_id, professional_id);
create table if not exists public.appointment_groups (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations(id) on delete cascade,
  branch_id uuid references public.branches(id) on delete set null,
  customer_id uuid not null references public.customers(id) on delete restrict,
  quote_id uuid references public.quotes(id) on delete set null,
  status text not null default 'scheduled' check (status in ('scheduled','in_progress','completed','cancelled')),
  notes text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (org_id, quote_id)
);
alter table public.appointments add column if not exists appointment_group_id uuid references public.appointment_groups(id) on delete set null;
create table if not exists public.appointment_group_items (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations(id) on delete cascade,
  appointment_group_id uuid not null references public.appointment_groups(id) on delete cascade,
  quote_item_id uuid references public.quote_items(id) on delete set null,
  appointment_id uuid references public.appointments(id) on delete set null,
  service_id uuid not null references public.services(id) on delete restrict,
  professional_id uuid references public.professionals(id) on delete set null,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  price numeric(12,2) not null default 0 check (price >= 0),
  status text not null default 'scheduled' check (status in ('scheduled','in_progress','completed','cancelled')),
  created_at timestamptz not null default now(),
  check (ends_at > starts_at),
  unique (org_id, appointment_id)
);
create index if not exists appointment_groups_org_customer_idx on public.appointment_groups(org_id, customer_id, created_at desc);
create index if not exists appointment_group_items_professional_time_idx on public.appointment_group_items(org_id, professional_id, starts_at, ends_at);
create index if not exists appointment_group_items_group_idx on public.appointment_group_items(org_id, appointment_group_id);
