  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations(id) on delete cascade,
  professional_id uuid not null,
  auth_user_id uuid not null references auth.users(id) on delete cascade,
  cpf_hmac bytea not null,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint professional_login_identity_professional_fk
    foreign key (org_id, professional_id)
    references public.professionals(org_id, id) on delete cascade,
  constraint professional_login_identity_org_cpf_unique unique (org_id, cpf_hmac),
  constraint professional_login_identity_user_unique unique (auth_user_id),
  constraint professional_login_identity_professional_unique unique (org_id, professional_id)
);
alter table private.professional_login_identities enable row level security;
revoke all on private.professional_login_identities from anon, authenticated;

