
create schema if not exists private;

create or replace function private.current_professional_id(target_org uuid)
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select p.id
  from public.professionals p
  join public.org_memberships m
    on m.org_id = p.org_id
   and m.user_id = (select auth.uid())
   and m.status = 'active'
   and m.role = 'professional'
  where p.org_id = target_org
    and p.profile_id = (select auth.uid())
    and p.active = true
  limit 1;
$$;

revoke all on function private.current_professional_id(uuid) from public, anon;
grant usage on schema private to authenticated;
grant execute on function private.current_professional_id(uuid) to authenticated;

