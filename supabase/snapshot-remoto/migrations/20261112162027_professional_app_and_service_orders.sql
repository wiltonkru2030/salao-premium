create table if not exists public.service_orders (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations(id) on delete cascade,
  branch_id uuid,
  customer_id uuid,
  appointment_id uuid,
  order_number bigint generated by default as identity,
  assigned_professional_id uuid,
  status text not null default 'open'
    check (status in ('open','in_progress','awaiting_payment','partially_paid','closed','cancelled')),
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  discount numeric(12,2) not null default 0 check (discount >= 0),
  total numeric(12,2) not null default 0 check (total >= 0),
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  created_by_type text not null default 'salon'
    check (created_by_type in ('customer','salon','professional')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint service_orders_org_id_id_unique unique (org_id,id),
  constraint service_orders_org_branch_fk foreign key (org_id,branch_id)
    references public.branches(org_id,id),
  constraint service_orders_org_customer_fk foreign key (org_id,customer_id)
    references public.customers(org_id,id),
  constraint service_orders_org_appointment_fk foreign key (org_id,appointment_id)
    references public.appointments(org_id,id),
  constraint service_orders_org_professional_fk foreign key (org_id,assigned_professional_id)
    references public.professionals(org_id,id)
);
create index if not exists service_orders_org_created_idx
  on public.service_orders(org_id,created_at desc);
create index if not exists service_orders_org_professional_idx
  on public.service_orders(org_id,assigned_professional_id,status);

create table if not exists public.service_order_items (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null,
  order_id uuid not null,
  item_type text not null check (item_type in ('service','product')),
  service_id uuid,
  product_id uuid,
  professional_id uuid,
  description text not null,
  quantity numeric(12,3) not null default 1 check (quantity > 0),
  unit_price numeric(12,2) not null default 0 check (unit_price >= 0),
  discount numeric(12,2) not null default 0 check (discount >= 0),
  total numeric(12,2) not null default 0 check (total >= 0),
  performed_at timestamptz,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint service_order_items_order_fk foreign key (org_id,order_id)
    references public.service_orders(org_id,id) on delete cascade,
  constraint service_order_items_service_fk foreign key (org_id,service_id)
    references public.services(org_id,id),
  constraint service_order_items_product_fk foreign key (org_id,product_id)
    references public.products(org_id,id),
  constraint service_order_items_professional_fk foreign key (org_id,professional_id)
    references public.professionals(org_id,id),
  constraint service_order_items_type_ref_check check (
    (item_type='service' and service_id is not null and product_id is null)
    or (item_type='product' and product_id is not null and service_id is null)
  )
);
create index if not exists service_order_items_org_order_idx
  on public.service_order_items(org_id,order_id);
create index if not exists service_order_items_org_professional_idx
  on public.service_order_items(org_id,professional_id,created_at desc);

alter table public.service_orders enable row level security;
alter table public.service_order_items enable row level security;

drop policy if exists appointments_select_member on public.appointments;
create policy appointments_select_admin_or_own_professional
on public.appointments for select to authenticated
using (
  private.has_org_role(org_id, array['owner','admin','manager','receptionist','finance','viewer'])
  or (professional_id = private.current_professional_id(org_id))
);

drop policy if exists commissions_select_member on public.commissions;
create policy commissions_select_admin_or_own_professional
on public.commissions for select to authenticated
using (
  private.has_org_role(org_id, array['owner','admin','manager','finance','viewer'])
  or (professional_id = private.current_professional_id(org_id))
);

create policy service_orders_select_admin_or_own_professional
on public.service_orders for select to authenticated
using (
  private.has_org_role(org_id, array['owner','admin','manager','receptionist','finance','viewer'])
  or assigned_professional_id = private.current_professional_id(org_id)
);

create policy service_orders_insert_staff
on public.service_orders for insert to authenticated
with check (
  private.has_org_role(org_id, array['owner','admin','manager','receptionist'])
);

create policy service_orders_update_admin
on public.service_orders for update to authenticated
using (private.has_org_role(org_id, array['owner','admin','manager']))
with check (private.has_org_role(org_id, array['owner','admin','manager']));

create policy service_order_items_select_admin_or_own_professional
on public.service_order_items for select to authenticated
using (
  private.has_org_role(org_id, array['owner','admin','manager','receptionist','finance','viewer'])
  or professional_id = private.current_professional_id(org_id)
);

create policy service_order_items_insert_admin_or_own_service
on public.service_order_items for insert to authenticated
with check (
  private.has_org_role(org_id, array['owner','admin','manager','receptionist'])
  or (
    item_type = 'service'
    and professional_id = private.current_professional_id(org_id)
    and exists (
      select 1 from public.service_orders o
      where o.id = order_id and o.org_id = org_id
        and o.status in ('open','in_progress')
        and o.assigned_professional_id = professional_id
    )
  )
);

create policy service_order_items_update_admin
on public.service_order_items for update to authenticated
using (private.has_org_role(org_id, array['owner','admin','manager']))
with check (private.has_org_role(org_id, array['owner','admin','manager']));

create policy service_order_items_delete_admin
on public.service_order_items for delete to authenticated
using (private.has_org_role(org_id, array['owner','admin','manager']));

grant select, insert, update on public.service_orders to authenticated;
grant select, insert, update, delete on public.service_order_items to authenticated;
